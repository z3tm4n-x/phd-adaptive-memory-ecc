"""Small directed-decimal report from exact rational result objects."""
import json
import engine as e

LABEL={'combined':'ERR + монитор','monitor-only':'Только монитор','ERR-only':'Только ERR (модель)'}


def n(v,digits=9,up=False):
    return '—' if v is None else e.decimal_text(e.F(v),upward=up,places=digits)


def pct(v,up=True):return n(100*e.F(v),7,up)+'%' if v is not None else '—'


